#!/usr/bin/env python3
"""The UI API's kinds and props as C: tests/uitree_contract/contract.json
into two headers and a list, generated, committed and never edited by hand;
tests/test_uitree_schema.py fails when either no longer matches.

  * native/moy_uitree/moy_uitree_schema.h: the table `uit_check_prop`
    (native/moy_uitree/moy_uitree_check.c) checks every front's props against;
  * sdk/include/moybyte/uitree_schema.h: a compiled app's names for them --
    the kinds by the engine's numbers (moy_uitree.h's enum, each a contract
    kind), each kind's name, a word prop's words, and a typed setter per
    prop (sdk/include/moybyte/uitree.h includes it).
  * docs/app_api_v1.md's freeze list (its "Stability" section): every name
    the contract holds, between its two markers.

    tools/gen_uitree_schema.py           write the headers
    tools/gen_uitree_schema.py --check   exit 1 where a header is stale
"""
import json
import os
import re
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTRACT = os.path.join(ROOT, "tests", "uitree_contract", "contract.json")
HEADER = os.path.join(ROOT, "native", "moy_uitree", "moy_uitree_schema.h")
ENGINE = os.path.join(ROOT, "native", "moy_uitree", "moy_uitree.h")
SDK = os.path.join(ROOT, "sdk", "include", "moybyte", "uitree_schema.h")
DOC = os.path.join(ROOT, "docs", "app_api_v1.md")

# a contract type's number in the table (moy_uitree.h's UIT_T_*); `word:A,B` is WORD with its words
TYPES = ("tpl", "cond", "name", "action", "hook", "action|hook", "int", "bool", "list", "lit", "fn",
         "key", "table", "takes", "text", "word", "list:tpl", "list:action", "conds", "list|conds", "int|word", "int|name")
F_DESIGNED = 1          # the spec designs it; no engine builds it yet


def _words(t):
    """A word type's words, comma-separated (`word:A,B`, `int|word:A,B`), or None."""
    return t.split(":", 1)[1] if t.startswith(("word:", "int|word:")) else None


def _type(t):
    return TYPES.index(t.split(":", 1)[0] if _words(t) else t) + 1


def _c(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def render(contract):
    kinds = contract["kinds"]
    common = contract["common_props"]
    child = contract["child_props"]
    props, rows = [], []
    for k, d in kinds.items():
        first = len(props)
        own = d.get("props", {})
        if k != "page":
            for p, pd in common.items():
                if p not in own:
                    props.append((p, pd["type"], 0))
        for p, pd in own.items():
            props.append((p, pd["type"], F_DESIGNED if pd.get("designed") else 0))
        if k != "page":
            for p in child:
                if p not in own:
                    props.append((p, "int" if p == "span" else "bool", 0))
        rows.append((k, first, len(props) - first, F_DESIGNED if d.get("designed") else 0))
    out = ["// GENERATED by tools/gen_uitree_schema.py from tests/uitree_contract/contract.json",
           "// (%s): never edit it; regenerate. Read by moy_uitree_check.c alone." % contract["spec"],
           "#ifndef MOY_UITREE_SCHEMA_H", "#define MOY_UITREE_SCHEMA_H", "",
           "enum {",
           "    " + ",\n    ".join("UIT_T_%s%s" % (t.replace("|", "_").replace(":", "_").upper(), " = 1" if i == 0 else "")
                                  for i, t in enumerate(TYPES)),
           "};", "#define UIT_SF_DESIGNED %d       // the spec designs it; no engine builds it yet" % F_DESIGNED, "",
           "// the table's names and words, each once, NUL-ended: a row holds offsets into it (0: none)",
           "static const char UIT_SSTR[] ="]
    blob, at = [""], {"": 0}
    size = 1

    def off(text):
        nonlocal size
        if text not in at:
            at[text] = size
            blob.append(text)
            size += len(text) + 1
        return at[text]
    prow = [(off(p), off(_words(t)) if _words(t) else 0, _type(t), f) for p, t, f in props]
    krow = [(off(k), first, n, f) for k, first, n, f in rows]
    assert size < 0x10000
    out += ['    "\\0"'] + ['    %s\\0"' % _c(text)[:-1] for text in blob[1:]] + ['    ;', "",
            "typedef struct {", "    uint16_t name;              // UIT_SSTR + name",
            "    uint16_t words;             // a word prop's words, comma-separated: UIT_SSTR + words; else 0",
            "    uint8_t type;               // UIT_T_*", "    uint8_t flags;              // UIT_SF_*",
            "} uit_sprop_t;", "",
            "typedef struct {", "    uint16_t name;", "    uint16_t first;             // its props: UIT_SPROPS[first, first + n)",
            "    uint8_t n;", "    uint8_t flags;", "} uit_skind_t;", "",
            "static const uit_sprop_t UIT_SPROPS[] = {"]
    for p, w, t, f in prow:
        out.append("    {%d, %d, %d, %d}," % (p, w, t, f))
    out += ["};", "", "static const uit_skind_t UIT_SKINDS[] = {"]
    for k, first, n, f in krow:
        out.append("    {%d, %d, %d, %d}," % (k, first, n, f))
    out += ["};", "",
            "// a retired prop (NAME, or NAME@KIND for one kind's) and what replaces it",
            "static const char *const UIT_SRETIRED[][2] = {"]
    for p, why in contract["retired"]["props"].items():
        out.append("    {%s, %s}," % (_c(p), _c(why)))
    out += ["};", "",
            "// what each type takes, for a message (UIT_T_* - 1)",
            "static const char *const UIT_STYPES[] = {"]
    names = contract["types"]
    for t in TYPES:
        key = t + ":A,B" if t.endswith("word") else "list:T" if t.startswith("list:") else t
        what = names[key] if not t.startswith("list:") else "a list of " + names[t[5:]].split(" ", 1)[1] + "s"
        out.append("    %s," % _c(what))
    out += ["};", "", "// each type's name in the contract (UIT_T_* - 1)", "static const char *const UIT_SKEYS[] = {"]
    out += ["    %s," % _c(t) for t in TYPES]
    out += ["};", "", "#endif", ""]
    return "\n".join(out)


def engine_kinds(header):
    """The engine's kinds in its numbering (moy_uitree.h's enum from UIT_PAGE = 1), lower-case."""
    body = re.search(r"enum \{\s*UIT_PAGE = 1,(.*?)UIT_KINDS", header, re.S).group(1)
    return ["page"] + [k.lower() for k in re.findall(r"UIT_(\w+)", re.sub(r"//[^\n]*", "", body))]


def render_sdk(contract, kinds):
    props = {}
    for k in kinds:
        assert k in contract["kinds"], "the engine's kind %r is not the contract's" % k
    for d in [{"props": contract["common_props"]}] + list(contract["kinds"].values()):
        for p, pd in d.get("props", {}).items():
            props.setdefault(p, []).append(pd["type"])
    out = ["// GENERATED by tools/gen_uitree_schema.py from tests/uitree_contract/contract.json",
           "// (%s) and native/moy_uitree/moy_uitree.h's kinds: never edit it; regenerate." % contract["spec"],
           "// Included by moybyte/uitree.h, whose ut_prop_ and ut_prop_int_ the setters call.",
           "#ifndef MOYBYTE_UITREE_SCHEMA_H", "#define MOYBYTE_UITREE_SCHEMA_H", "",
           "// A node's kind (uitree_node), by the engine's number.", "enum {"]
    out += textwrap.wrap(" ".join("UT_%s%s," % (k.upper(), " = 1" if i == 0 else "") for i, k in enumerate(kinds)),
                         96, initial_indent="    ", subsequent_indent="    ", break_on_hyphens=False)
    out += ["};", "", "// Each kind's name by its number: an unkeyed node's key is its kind's name and its place.",
            "static const char *const ut_kind_names_[] = {"]
    out += textwrap.wrap('"", ' + " ".join(_c(k) + "," for k in kinds), 96, initial_indent="    ",
                         subsequent_indent="    ", break_on_hyphens=False)
    out += ["};",
            "", "// A word prop's words (`off` takes the action's: \"hide\", \"grey\")."]
    for p in sorted(props):
        words = []
        for t in props[p]:
            words += [w for w in (_words(t) or "").split(",") if w and w not in words]
        if p != "off":
            out += ['#define UT_%s_%s "%s"' % (p.upper(), w.upper(), w) for w in words]
    out += ["", "// Each prop of the node made last, by its contract type: an int, a bool, else its",
            "// source (a list prop's items one call each). A prop a kind lacks is refused at its call."]
    for p in sorted(props):
        ts = set(props[p])
        if ts == {"int"}:
            out.append("static inline int32_t ut_p_%s(int32_t v) { return ut_prop_int_(%s, v); }" % (p, _c(p)))
        elif ts == {"bool"}:
            out.append('static inline int32_t ut_p_%s(int v) { return ut_prop_(%s, v ? "True" : "False"); }' % (p, _c(p)))
        else:
            out.append("static inline int32_t ut_p_%s(const char *v) { return ut_prop_(%s, v); }" % (p, _c(p)))
    out += ["", "#endif", ""]
    return "\n".join(out)


FREEZE_BEGIN = "<!-- the freeze list: generated by tools/gen_uitree_schema.py from the contract; never edit it -->"
FREEZE_END = "<!-- the freeze list ends -->"


def _ty(t):
    """A prop's type as the freeze list says it: a word prop its words."""
    w = _words(t)
    if w is None:
        return t.replace("|", " or ").replace("list:", "list of ")
    pre = "int or " if t.startswith("int|") else ""
    return pre + " ".join('`"%s"`' % x for x in w.split(","))


def _props(ps):
    return ", ".join("`%s` %s" % (p, _ty(d["type"])) for p, d in ps.items() if not d.get("designed")) or "none"


def render_freeze(contract):
    """docs/app_api_v1.md's freeze list: every built name of the contract,
    then the names it designs and no front builds."""
    kinds = contract["kinds"]
    out = [FREEZE_BEGIN, "",
           "| kind | level | head | props |", "|---|---|---|---|"]
    for k, d in kinds.items():
        if d.get("designed"):
            continue
        head = d["head"]
        if isinstance(head, dict):
            head = ", ".join("%s %s" % (f, h) for f, h in head.items())
        head = (head or "none") + (", optional" if d.get("head_optional") else "")
        if "made_by" in d:
            head += ", made by its parent"
        out.append("| `%s` | %d | %s | %s |" % (k, d["level"], head, _props(d["props"])))
    roles = contract["roles"]
    out += ["",
            "- **Every node but the page:** %s. **A child of a row or a grid:** %s." % (
                _props(contract["common_props"]), ", ".join("`%s`" % p for p in contract["child_props"])),
            "- **An action:** %s. **A hook:** %s." % (_props(contract["action_props"]), _props(contract["hook_props"])),
            "- **`takes=`:** %s. **`off=`:** %s." % (
                ", ".join("`%s`" % t for t, d in contract["takes"].items() if not d.get("designed")),
                ", ".join("`%s`" % o for o in contract["offs"])),
            "- **Roles an app's keys name:** %s; the shell's own: %s." % (
                ", ".join("`%s`" % r for r, d in roles.items() if d["owner"] == "app" and not d.get("designed")),
                ", ".join("`%s`" % r for r, d in roles.items() if d["owner"] != "app")),
            "- **Verbs** (besides a kind's, its name): %s. **Queries:** %s." % (
                ", ".join("`%s`" % v for v, d in contract["verbs"].items() if not d.get("designed")),
                ", ".join("`%s`" % q for q in contract["queries"])),
            "- **App fields (`ui.app`):** %s. **System values (`@NAME`):** %s." % (
                ", ".join("`%s`" % f for f in contract["app_fields"]),
                ", ".join("`%s` %s" % (v, t) for v, t in contract["system_values"].items())),
            "- **Error codes:** %s." % ", ".join(sorted(contract["codes"])),
            "- **Reserved codes**, never raised: %s." % ", ".join(sorted(contract["reserved_codes"])),
            "- **Retired names**, each refused with its replacement (N04): %s." % "; ".join(
                "%s %s" % (sec.replace("_", " "), ", ".join("`%s`" % n for n in sorted(names)))
                for sec, names in contract["retired"].items()),
            ]
    designed = []
    for k, d in kinds.items():
        if d.get("designed"):
            designed.append("`%s`" % k)
            continue
        designed += ["`%s.%s`" % (k, p) for p, pd in d["props"].items() if pd.get("designed")]
    for name, table in (("action", "action_props"), ("hook", "hook_props")):
        designed += ["%s `%s`" % (name, p) for p, d in contract[table].items() if d.get("designed")]
    designed += ["`takes=\"%s\"`" % t for t, d in contract["takes"].items() if d.get("designed")]
    designed += ["role `%s`" % r for r, d in roles.items() if d.get("designed")]
    designed += ["verb `%s`" % v for v, d in contract["verbs"].items() if d.get("designed")]
    out += ["- **Named and not built** (`designed`: every front refuses each, N01): %s." % ", ".join(designed),
            "", FREEZE_END]
    return "\n".join(out)


def _spliced(doc, section):
    """docs/app_api_v1.md with its freeze list replaced by `section`."""
    a, b = doc.index(FREEZE_BEGIN), doc.index(FREEZE_END) + len(FREEZE_END)
    return doc[:a] + section + doc[b:]


def main(argv):
    with open(CONTRACT, encoding="utf-8") as f:
        contract = json.load(f)
    with open(ENGINE, encoding="utf-8") as f:
        kinds = engine_kinds(f.read())
    with open(DOC, encoding="utf-8") as f:
        doc = _spliced(f.read(), render_freeze(contract))
    stale = 0
    for path, text in ((HEADER, render(contract)), (SDK, render_sdk(contract, kinds)), (DOC, doc)):
        if "--check" not in argv:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            continue
        with open(path, encoding="utf-8") as f:
            if f.read() != text:
                print("%s is stale: run tools/gen_uitree_schema.py" % os.path.relpath(path, ROOT))
                stale = 1
    return stale


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
