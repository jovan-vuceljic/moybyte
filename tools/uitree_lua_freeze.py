#!/usr/bin/env python3
"""Freeze the UI tree API's Lua layer into a board image.

    python tools/uitree_lua_freeze.py MODULES_DIR

writes MODULES_DIR/uitree_lua.py, `SRC = {name: bytes}` over the layer's two
files (runtime/run/lua_ext.py's UITREE_FILE and UITREE_BACK), which the image
freezes: each value is the file's text raw-deflated with a window of
2**WBITS bytes, a bytes constant in flash. moycore takes a bytes chunk as
that (native/moycore/modmoycore.c's run_chunk): Lua's parser reads it as it
inflates, through a ring of MOYCORE_Z_WINDOW bytes, so the layer costs a
board no RAM until a cart that declares `moybyte.uitree` runs, and the
window while it loads. `lua_ext.uitree_source` reads it where it is staged.

Each text is the file with its comments and the spaces around its lines
dropped, and every line kept where it was, so a fault inside the layer still
names the line of runtime/run/uitree.lua it is on.
"""
import os
import re
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.join(os.path.dirname(HERE), "runtime", "run")
sys.path.insert(0, RUN)
import lua_ext  # noqa: E402

FILES = (lua_ext.UITREE_FILE, lua_ext.UITREE_BACK)
WBITS = 12
_LONG = re.compile(r"\[(=*)\[")


def _long_end(src, i, eq):
    """The index after the `]=*]` closing a long bracket of level `eq` opened
    before `i`."""
    end = src.find("]" + eq + "]", i)
    if end < 0:
        raise ValueError("an unfinished long bracket")
    return end + len(eq) + 2


def strip(src):
    """`src` without its comments and the blanks around and between its
    tokens collapsed to one, each newline kept: the same chunk to Lua's
    parser, line for line."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if c == "-" and src.startswith("--", i):
            m = _LONG.match(src, i + 2)
            if m:
                j = _long_end(src, m.end(), m.group(1))
                out.append("\n" * src.count("\n", i, j))
            else:
                j = src.find("\n", i)
                j = n if j < 0 else j
            i = j
        elif c in "'\"":
            j = i + 1
            while src[j] != c:
                if src[j] == "\n":
                    raise ValueError("an unfinished string")
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1])
            i = j + 1
        elif c == "[" and _LONG.match(src, i):
            m = _LONG.match(src, i)
            j = _long_end(src, m.end(), m.group(1))
            out.append(src[i:j])
            i = j
        elif c in " \t\r\n":
            j = i
            while j < n and src[j] in " \t\r\n":
                j += 1
            nl = src.count("\n", i, j)
            out.append("\n" * nl if nl else " ")
            i = j
        else:
            out.append(c)
            i += 1
    text = "".join(out)
    return re.sub(r" ?\n ?", "\n", text).lstrip(" ").rstrip(" \n") + "\n"


def deflate(text):
    """`text` raw-deflated, its window 2**WBITS bytes."""
    z = zlib.compressobj(9, zlib.DEFLATED, -WBITS, 9)
    return z.compress(text.encode()) + z.flush()


def module():
    """The text of uitree_lua.py."""
    lines = ["# GENERATED by tools/uitree_lua_freeze.py from runtime/run/: do not edit.",
             "SRC = {"]
    for name in FILES:
        with open(os.path.join(RUN, name)) as f:
            lines.append("    %r: %r," % (name, deflate(strip(f.read()))))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__.strip().splitlines()[2].strip())
    if argv[1] in ("-h", "--help"):
        print(__doc__.strip())
        return
    out = os.path.join(argv[1], "uitree_lua.py")
    with open(out, "w") as f:
        f.write(module())


if __name__ == "__main__":
    main(sys.argv)
